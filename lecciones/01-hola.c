/* Primer programa: separar declaraciones, instrucciones y resultado. */
#include <stdio.h> /* Declara printf; no pega su implementación aquí. */

int main(void) { /* void indica que esta función no recibe parámetros. */
    printf("Hola, C!\n"); /* \n termina la línea; ; termina la instrucción. */
    return 0; /* El entorno recibe 0 si terminamos correctamente. */
}
